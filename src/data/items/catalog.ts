/**
 * The item catalog. Add, rename or remove items here; ids must be unique and never change
 * once players own the item (inventories store the id). Items in the same star tier are
 * equally likely to be pulled.
 *
 * Every item goes in one slot (weapon, armor, or treasure) and lists the effects it gives while
 * equipped. Effect strength depends on the star tier and lives in the settings
 * (equipment.<effect>.<stars>), so a 3-star item is always stronger than a 1-star one that
 * lists the same effect. Weapons lean toward offense and armor toward defense, plus a perk.
 * Raid gear that heals (raidSupport, healSplash, healBonus) is always a weapon. Moving an item
 * between weapon and armor is fine once members own it: syncGearSlots (services/migrate.ts) moves
 * worn copies into their new slot on the next start.
 * Unique treasures (slot 'treasure') are a third slot every member has, on top of their weapon
 * and armor: it stacks with those two, but only one unique treasure can be equipped at a
 * time (the 4-star unique treasures all compete for that one slot).
 *
 * An item can be made exclusive with `usableBy: [MEMBERS.<name>, ...]` (add the member to
 * data/members.ts first). Anyone can pull, own and equip it, but only the listed members (and
 * the admin, for testing) get its effects. Leave `usableBy` out and everyone can use it.
 *
 * An item marked `raidDrop: true` can't be pulled from the gacha: it only drops from raid bosses.
 *
 * An item marked `limited: true` is never on the standard banner: it is only pulled from the limited
 * banner, while it is one of the banner's featured items (items/banner.ts).
 *
 * An item marked `tmDrop: true` is TechnoMagic gear: never pulled, only dropped by the TechnoMagic Raid,
 * and only its heroes wear it. It has no perks: each copy's stats are the potentials it rolled as it dropped
 * (ItemCopyDoc.tmPotentials, data/tm-potentials.ts).
 *
 * An item with `uniqueWeapon: '<hero id>'` is that hero's unique weapon: only pulled from the Hero Item
 * banner, and only that hero wields it. One with `uniqueTreasure: { hero, skill }` is one of that hero's four unique
 * treasures (its `skill`th: UT1 to UT4): only pulled from the Hero Item banner too, and only that hero wears it.
 */
